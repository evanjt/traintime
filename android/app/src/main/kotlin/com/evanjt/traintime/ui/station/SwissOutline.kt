@Composable
fun SwissOutlineBackdrop(color: Color, modifier: Modifier = Modifier, width: Dp = 300.dp) {
    Canvas(modifier = modifier.width(width).aspectRatio(ASPECT)) {
        val path = Path()
        POINTS.forEachIndexed { i, p ->
            val x = p.x * size.width
            val y = p.y * size.height
            if (i == 0) path.moveTo(x, y) else path.lineTo(x, y)
        }
        path.close()
        drawPath(
            path,
            color = color,
            style = Stroke(
                width = 1.5.dp.toPx(),
                pathEffect = PathEffect.dashPathEffect(floatArrayOf(10f, 12f)),
            ),
        )
    }
}
